CREATE TABLE IF NOT EXISTS asset_storage_provider (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id VARCHAR(36) NOT NULL,
    provider_code VARCHAR(40) NOT NULL,
    provider_name VARCHAR(100) NOT NULL,
    bucket_name VARCHAR(120) NOT NULL,
    endpoint_url VARCHAR(500) NULL,
    public_base_url VARCHAR(500) NOT NULL,
    region_code VARCHAR(80) NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_asset_storage_provider_public_id UNIQUE (public_id),
    CONSTRAINT uk_asset_storage_provider_code UNIQUE (provider_code)
);

CREATE TABLE IF NOT EXISTS asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id VARCHAR(36) NOT NULL,
    provider_code VARCHAR(40) NOT NULL,
    bucket_name VARCHAR(120) NOT NULL,
    object_key VARCHAR(500) NOT NULL,
    public_url VARCHAR(900) NOT NULL,
    thumbnail_url VARCHAR(900) NULL,
    asset_type VARCHAR(50) NOT NULL,
    owner_type VARCHAR(50) NOT NULL,
    owner_id VARCHAR(120) NULL,
    content_type VARCHAR(120) NOT NULL,
    file_size_bytes BIGINT NULL,
    width_pixels INT NULL,
    height_pixels INT NULL,
    alt_text VARCHAR(255) NULL,
    checksum_sha256 VARCHAR(64) NULL,
    visibility VARCHAR(30) NOT NULL,
    asset_status VARCHAR(30) NOT NULL,
    created_by_user_public_id VARCHAR(36) NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_asset_public_id UNIQUE (public_id),
    CONSTRAINT fk_asset_provider_code FOREIGN KEY (provider_code) REFERENCES asset_storage_provider (provider_code)
);

CREATE TABLE IF NOT EXISTS asset_variant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id VARCHAR(36) NOT NULL,
    asset_public_id VARCHAR(36) NOT NULL,
    variant_code VARCHAR(50) NOT NULL,
    object_key VARCHAR(500) NOT NULL,
    public_url VARCHAR(900) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    file_size_bytes BIGINT NULL,
    width_pixels INT NULL,
    height_pixels INT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_asset_variant_public_id UNIQUE (public_id),
    CONSTRAINT uk_asset_variant_code UNIQUE (asset_public_id, variant_code),
    CONSTRAINT fk_asset_variant_asset_public_id FOREIGN KEY (asset_public_id) REFERENCES asset (public_id)
);

DROP INDEX IF EXISTS uk_asset_provider_object;
CREATE INDEX IF NOT EXISTS idx_asset_provider_code ON asset (provider_code);
CREATE INDEX IF NOT EXISTS idx_asset_owner ON asset (owner_type, owner_id);
CREATE INDEX IF NOT EXISTS idx_asset_type_status ON asset (asset_type, asset_status);
CREATE INDEX IF NOT EXISTS idx_asset_visibility ON asset (visibility);
CREATE INDEX IF NOT EXISTS idx_asset_provider_object ON asset (provider_code, bucket_name, object_key);

