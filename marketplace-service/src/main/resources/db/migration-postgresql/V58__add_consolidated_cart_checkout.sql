-- Durable consolidated physical cart checkout: one parent checkout per buyer idempotency key with
-- one child order_header per purchased listing line. Legacy single-item orders keep checkout_id NULL.
CREATE TABLE marketplace_checkout (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id VARCHAR(36) NOT NULL,
    customer_user_public_id VARCHAR(100) NOT NULL,
    cart_public_id VARCHAR(50) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    checkout_status VARCHAR(40) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    item_amount DECIMAL(12,2) NOT NULL,
    platform_fee_amount DECIMAL(12,2) NOT NULL,
    customer_total_amount DECIMAL(12,2) NOT NULL,
    provider_amount DECIMAL(12,2) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_marketplace_checkout_public_id UNIQUE (public_id),
    CONSTRAINT uk_marketplace_checkout_idempotency UNIQUE (customer_user_public_id, idempotency_key)
);

CREATE INDEX idx_marketplace_checkout_customer_created ON marketplace_checkout (customer_user_public_id, created_at);

ALTER TABLE order_header ADD COLUMN checkout_id BIGINT NULL;
ALTER TABLE order_header ADD COLUMN quantity INTEGER NOT NULL DEFAULT 1;
ALTER TABLE order_header ADD COLUMN unit_price_amount DECIMAL(12,2) NULL;
ALTER TABLE order_header ADD COLUMN cart_item_public_id VARCHAR(50) NULL;
ALTER TABLE order_header ADD CONSTRAINT ck_order_header_quantity_positive CHECK (quantity > 0);
ALTER TABLE order_header ADD CONSTRAINT fk_order_header_checkout FOREIGN KEY (checkout_id) REFERENCES marketplace_checkout (id);
CREATE UNIQUE INDEX uk_order_header_checkout_listing ON order_header (checkout_id, listing_id);
