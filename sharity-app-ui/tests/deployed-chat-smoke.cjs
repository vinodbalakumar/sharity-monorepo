// Real deployed-site verification. No API fixtures, credentials, orders or payment mutations.
const { chromium, firefox, webkit, expect } = require('@playwright/test');
const fs = require('node:fs');
const base = (process.argv[2] || 'https://vinodbalakumar.com').replace(/\/$/, '');
const targetLabel = base.startsWith('https:') ? 'public' : 'local';
(async () => {
  const engine = { chromium, firefox, webkit }[process.env.SHARITY_SMOKE_BROWSER || 'chromium'];
  if (!engine) throw new Error('Unsupported verification browser');
  const ipv4 = process.env.SHARITY_SMOKE_IPV4;
  const args = ipv4 && engine === chromium ? ['--disable-quic', `--host-resolver-rules=MAP vinodbalakumar.com ${ipv4}`] : [];
  const browser = await engine.launch({ args });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const evidence = { base, verifiedAt: new Date().toISOString(), browser: process.env.SHARITY_SMOKE_BROWSER || 'chromium', ipv4Transport: ipv4 || null, tests: {}, chatTimingsMs: [], responses: [] };
  page.on('response', response => {
    const url = new URL(response.url());
    if (url.origin === base && url.pathname.startsWith('/bff/ai/')) evidence.responses.push({ path: url.pathname.replace(/\/conversations\/[a-f0-9-]+$/, '/conversations/{id}'), method: response.request().method(), status: response.status() });
  });
  try {
    const loaded = await page.goto(`${base}/chat`, { waitUntil: 'domcontentloaded' });
    expect(loaded.status()).toBe(200);
    await expect(page.getByRole('heading', { name: 'Welcome to Sharity AI' })).toBeVisible({ timeout: 60000 });
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Welcome to Sharity AI' })).toBeVisible({ timeout: 45000 });
    evidence.tests.directChatAndRefresh = true;
    async function ask(question) {
      const started = Date.now();
      await page.getByLabel('Message Sharity AI').fill(question);
      const pending = page.waitForResponse(response => response.url().endsWith('/bff/ai/chat') && response.request().method() === 'POST', { timeout: 110000 });
      await page.getByRole('button', { name: 'Send message' }).click();
      const response = await pending;
      evidence.chatTimingsMs.push(Date.now() - started);
      expect(response.status()).toBe(200);
      return response.json();
    }
    const founder = await ask('Who founded Sharity?');
    expect(founder.generation).toBe('STRUCTURED');
    expect(founder.response).toContain('Vinod Balakumar Panchaparvala');
    expect(founder.response).not.toContain('@gmail.com');
    await expect(page.getByTestId('message-assistant')).toHaveCount(1);
    evidence.tests.approvedFounderAndPrivateEmail = true;
    await expect(page.getByTestId('response-time')).toHaveCount(1);
    const code = await ask('Write a short Java program to reverse a string.');
    expect(code.generation).toBe('OLLAMA');
    expect(code.response).toContain('```');
    await expect(page.getByTestId('message-assistant')).toHaveCount(2, { timeout: 15000 });
    await expect(page.getByRole('button', { name: 'Copy code' })).toBeVisible();
    evidence.tests.realDeployedQwenCode = true;
    await expect(page.getByTestId('response-time')).toHaveCount(2);
    await expect(page.getByTestId('response-time').last()).toHaveText(/^Response time: (?:<0\.1|\d+\.\d) s$/);
    evidence.responseTimeLabels = await page.getByTestId('response-time').allTextContents();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByTestId('response-time').last().scrollIntoViewIfNeeded();
    await expect(page.getByTestId('response-time').last()).toBeInViewport();
    await page.screenshot({ path: '../outputs/deployed-chat-response-time-mobile.png' });
    await page.setViewportSize({ width: 1440, height: 1000 });
    evidence.tests.responseTimeLabelsDesktopAndMobile = true;
    expect(code.metrics.inputTokens).toBeGreaterThan(0);
    expect(code.metrics.outputTokens).toBeGreaterThan(0);
    expect(code.metrics.totalTokens).toBe(code.metrics.inputTokens + code.metrics.outputTokens);
    const totalTokens=code.metrics.totalTokens.toLocaleString();
    await page.getByTestId('message-assistant').last().getByRole('button', { name: 'Message info', exact: true }).click();
    await expect(page.getByTestId('message-info')).toContainText('Request sent:');
    await expect(page.getByTestId('message-info')).toContainText('Response received:');
    await expect(page.getByTestId('message-info')).toContainText(`Total tokens: ${totalTokens}`);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByTestId('message-info').scrollIntoViewIfNeeded();
    await page.screenshot({ path: '../outputs/deployed-chat-message-info-mobile.png' });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: 'Chat info', exact: true }).click();
    await expect(page.getByTestId('chat-info')).toContainText(`Total tokens: ${totalTokens}`);
    evidence.tokenUsage=code.metrics;
    evidence.tests.messageInfoAndChatTokenTotals=true;
    await page.getByRole('button', { name: 'Save chat', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Unsave chat', exact: true })).toBeVisible();
    await page.reload();
    await page.getByTestId('chat-sidebar').getByRole('button', { name: '★ Who founded Sharity?' }).click({ timeout: 45000 });
    await expect(page.getByTestId('message-assistant')).toHaveCount(2);
    await page.getByTestId('message-assistant').last().getByRole('button', { name: 'Message info', exact: true }).click();
    await expect(page.getByTestId('message-info')).toContainText('Server received:');
    await expect(page.getByTestId('message-info')).toContainText(`Total tokens: ${totalTokens}`);
    evidence.tests.persistedTimingAndTokenUsage=true;
    await page.screenshot({ path: '../outputs/deployed-sharity-ai-desktop.png' });
    await page.getByRole('button', { name: 'Delete chat', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Welcome to Sharity AI' })).toBeVisible();
    evidence.tests.mysqlHistorySaveReloadDeleteAndCsrf = true;
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole('button', { name: 'Send message' })).toBeInViewport();
    await page.getByRole('button', { name: 'Toggle theme' }).click();
    await expect(page.getByTestId('sharity-ai')).toHaveCSS('background-color', 'rgb(16, 28, 24)');
    await page.screenshot({ path: '../outputs/deployed-sharity-ai-mobile.png' });
    evidence.tests.mobileAndDarkTheme = true;
    const catalog = await context.request.get(`${base}/bff/public/marketplace-service/api/v1/marketplace/home`);
    expect(catalog.status()).toBe(200);
    evidence.tests.deployedPublicCatalog = true;
    const admin = await context.request.get(`${base}/bff/api/platform-ai-service/api/v1/admin/diagnostics`);
    expect([401, 403]).toContain(admin.status());
    evidence.tests.adminRequiresAuthentication = true;
    const login = await context.request.get(`${base}/bff/login`, { maxRedirects: 0 });
    expect(login.status()).toBe(302);
    expect(login.headers().location).toContain('/oauth2/authorization/');
    evidence.tests.oauthStartRoutePreserved = true;
    evidence.passed = true;
    console.log('PASS: deployed public chat, real Qwen, MySQL history, CSRF, mobile/theme, catalog, protected admin and OAuth start');
  } catch (error) {
    evidence.passed = false; evidence.error = String(error).slice(0, 800);
    await page.screenshot({ path: '../outputs/deployed-sharity-ai-failure.png' }).catch(() => {});
    console.error(error); process.exitCode = 1;
  } finally {
    fs.writeFileSync(`../outputs/deployed-chat-${targetLabel}-verification.json`, JSON.stringify(evidence, null, 2));
    fs.writeFileSync('../outputs/deployed-chat-verification.json', JSON.stringify(evidence, null, 2));
    await browser.close();
  }
})();
