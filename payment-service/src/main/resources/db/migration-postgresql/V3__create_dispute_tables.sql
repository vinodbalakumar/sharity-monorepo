CREATE TABLE dispute (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id VARCHAR(50) NOT NULL UNIQUE,
    customer_id VARCHAR(100) NOT NULL,
    order_id VARCHAR(100) NOT NULL,
    payment_id VARCHAR(100),
    dispute_reason VARCHAR(500) NOT NULL,
    dispute_description TEXT,
    dispute_status VARCHAR(50) DEFAULT 'OPENED',
    resolution_status VARCHAR(50),
    claimed_amount DECIMAL(19, 4),
    refunded_amount DECIMAL(19, 4) DEFAULT 0,
    currency_code VARCHAR(3) DEFAULT 'USD',
    merchant_id VARCHAR(100),
    evidence_count INT DEFAULT 0,
    notes TEXT,
    resolved_at TIMESTAMP,
    closed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_dispute_customer_id ON dispute (customer_id);
CREATE INDEX idx_dispute_order_id ON dispute (order_id);
CREATE INDEX idx_dispute_status ON dispute (dispute_status);
CREATE INDEX idx_dispute_created_at ON dispute (created_at);

CREATE TABLE dispute_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id VARCHAR(50) UNIQUE,
    dispute_id BIGINT NOT NULL,
    evidence_type VARCHAR(50) NOT NULL,
    file_url VARCHAR(500) NOT NULL,
    file_name VARCHAR(255),
    file_size BIGINT,
    description TEXT,
    uploaded_by VARCHAR(100),
    uploaded_at TIMESTAMP NOT NULL,
    FOREIGN KEY (dispute_id) REFERENCES dispute(id) ON DELETE CASCADE
);

CREATE INDEX idx_evidence_dispute_id ON dispute_evidence (dispute_id);

CREATE TABLE dispute_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(50) UNIQUE,
    dispute_id BIGINT NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    event_description TEXT,
    actor VARCHAR(100),
    visibility VARCHAR(50) DEFAULT 'BOTH',
    created_at TIMESTAMP NOT NULL,
    FOREIGN KEY (dispute_id) REFERENCES dispute(id) ON DELETE CASCADE
);

CREATE INDEX idx_event_dispute_id ON dispute_event (dispute_id);
CREATE INDEX idx_event_created_at ON dispute_event (created_at);
